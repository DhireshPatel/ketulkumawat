const ALKALI = new Set([3, 11, 19, 37, 55, 87]);
const ALKALINE_EARTH = new Set([4, 12, 20, 38, 56, 88]);
const METALLOIDS = new Set([5, 14, 32, 33, 51, 52]);
const NONMETALS = new Set([1, 6, 7, 8, 15, 16, 34]);
const HALOGENS = new Set([9, 17, 35, 53, 85]);
const NOBLE_GASES = new Set([2, 10, 18, 36, 54, 86]);
const POST_TRANSITION = new Set([13, 31, 49, 50, 81, 82, 83, 84]);
const GASES = new Set([1, 2, 7, 8, 9, 10, 17, 18, 36, 54, 86]);
const LIQUIDS = new Set([35, 80]);

function getCategory(z) {
  if (ALKALI.has(z)) return "Alkali Metals";
  if (ALKALINE_EARTH.has(z)) return "Alkaline Earth Metals";
  if (METALLOIDS.has(z)) return "Metalloids";
  if (NONMETALS.has(z)) return "Nonmetals";
  if (HALOGENS.has(z)) return "Halogens";
  if (NOBLE_GASES.has(z)) return "Noble Gases";
  if (POST_TRANSITION.has(z)) return "Post-Transition Metals";
  if (z >= 57 && z <= 71) return "Lanthanides";
  if (z >= 89 && z <= 103) return "Actinides";
  if (z >= 109) return "Unknown";
  return "Transition Metals";
}

function getPhase(z) {
  if (z >= 104) return "Unknown";
  if (GASES.has(z)) return "Gas";
  if (LIQUIDS.has(z)) return "Liquid";
  return "Solid";
}

// Returns { group, period } for the main table, or { fBlock: 1|2, column }
// for lanthanides (La-Lu) and actinides (Ac-Lr) shown in separate rows.
function getPosition(z) {
  if (z >= 57 && z <= 71) return { period: 6, fBlock: 1, column: 3 + (z - 57) };
  if (z >= 89 && z <= 103)
    return { period: 7, fBlock: 2, column: 3 + (z - 89) };

  if (z === 1) return { period: 1, group: 1 };
  if (z === 2) return { period: 1, group: 18 };
  if (z <= 4) return { period: 2, group: z - 2 };
  if (z <= 10) return { period: 2, group: z + 8 };
  if (z <= 12) return { period: 3, group: z - 10 };
  if (z <= 18) return { period: 3, group: z - 0 };
  if (z <= 36) return { period: 4, group: z - 18 };
  if (z <= 54) return { period: 5, group: z - 36 };
  if (z <= 56) return { period: 6, group: z - 54 };
  if (z <= 86) return { period: 6, group: z - 68 }; // Hf(72) -> 4 ... Rn(86) -> 18
  if (z <= 88) return { period: 7, group: z - 86 };
  return { period: 7, group: z - 100 }; // Rf(104) -> 4 ... Og(118) -> 18
}

export const elements = ROWS.map(
  ([
    atomicNumber,
    symbol,
    name,
    atomicMass,
    discovered,
    electronConfiguration,
    description,
  ]) => ({
    atomicNumber,
    symbol,
    name,
    atomicMass,
    category: getCategory(atomicNumber),
    phase: getPhase(atomicNumber),
    discovered,
    electronConfiguration,
    description,
    ...getPosition(atomicNumber),
  }),
);

export default elements;
